import { readFileSync } from 'node:fs';
import { getNoir, getBackend, getHashApi } from '../src/server/zk.js';
import { FIXED } from './golden-vectors.js';
import { hexToField, dayIndexFromISO } from '../src/shared/encoding.js';
import { nullifierFor } from '../src/shared/hash.js';
import { circuitInputs, expectedPublicInputs } from '../src/shared/witness.js';
const saved = JSON.parse(readFileSync(new URL('../spec/test-vectors.json', import.meta.url), 'utf8'));
const api = await getHashApi();
const v = saved.vectors[0];
const params = { campaignId: FIXED.campaignId, category: 3, dayFrom: dayIndexFromISO('2026-09-01'), dayTo: dayIndexFromISO('2026-09-30'), min: 20000, max: 50000 };
const nullifier = nullifierFor(api, FIXED.holderSecret, FIXED.campaignId);
const inputs = circuitInputs({ rows: v.rows, blind: hexToField(v.blind), holderSecret: FIXED.holderSecret, root: hexToField(v.root), params, recipientHash: hexToField(saved.recipient_hash), nullifier });
let t = Date.now(); const { witness } = await getNoir().execute(inputs); console.log('witness ms', Date.now() - t);
t = Date.now(); const backend = await getBackend(); console.log('backend init ms', Date.now() - t);
t = Date.now(); const proof = await backend.generateProof(witness); console.log('prove ms', Date.now() - t, 'proof bytes', proof.proof.length, 'pubinputs', proof.publicInputs.length);
const exp = expectedPublicInputs({ root: hexToField(v.root), params, recipientHash: hexToField(saved.recipient_hash), nullifier });
console.log('public inputs match expected:', JSON.stringify(proof.publicInputs) === JSON.stringify(exp));
t = Date.now(); console.log('verify', await backend.verifyProof(proof), 'ms', Date.now() - t);
const bad = { ...proof, publicInputs: [...proof.publicInputs] }; bad.publicInputs[7] = '0x' + '0'.repeat(63) + '1';
console.log('verify w/ swapped recipient hash', await backend.verifyProof(bad).catch((e) => 'threw: ' + e.message));
process.exit(0);
